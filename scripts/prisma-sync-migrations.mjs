/**
 * Copies supabase/migrations/*.sql into the layout Prisma Migrate expects.
 *
 *   supabase/migrations/0020_three_photo_minimum.sql
 *     -> prisma/migrations/0020_three_photo_minimum/migration.sql
 *
 * Why a copy rather than one directory: the Supabase CLI reads flat .sql files
 * from supabase/migrations for `supabase db reset`, and Prisma reads
 * folder/migration.sql. Neither will read the other's layout, and asking a
 * developer to keep two hand-written copies in step is asking for the day they
 * diverge. So one is written by hand and the other is generated, gitignored,
 * and rebuilt before every Prisma command.
 *
 * The copy is byte for byte. Prisma stores a checksum of migration.sql in
 * _prisma_migrations and refuses to run if a previously applied migration's
 * contents have changed, which is a feature worth keeping intact — reformatting
 * the copy would set that alarm off on every developer's machine.
 *
 * Ordering is lexicographic on the folder name, which is why the numeric prefix
 * is zero-padded. 0009 sorts before 0010; 9 would not.
 */
import {
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';

const SOURCE = path.join('supabase', 'migrations');
const TARGET = path.join('prisma', 'migrations');

if (!existsSync(SOURCE)) {
  console.error(`No ${SOURCE} directory. Run this from the repository root.`);
  process.exit(1);
}

mkdirSync(TARGET, { recursive: true });

// Prisma refuses to run without this, and uses it to check that the migrations
// were written for the database they are about to be applied to.
const lockPath = path.join(TARGET, 'migration_lock.toml');
const lock = '# Generated by scripts/prisma-sync-migrations.mjs. Do not edit.\nprovider = "postgresql"\n';
if (!existsSync(lockPath) || readFileSync(lockPath, 'utf8') !== lock) {
  writeFileSync(lockPath, lock);
}

const sources = readdirSync(SOURCE)
  .filter((file) => file.endsWith('.sql'))
  .sort();

let written = 0;
for (const file of sources) {
  const name = file.replace(/\.sql$/, '');
  const sql = readFileSync(path.join(SOURCE, file), 'utf8');
  const destination = path.join(TARGET, name, 'migration.sql');

  if (existsSync(destination) && readFileSync(destination, 'utf8') === sql) continue;

  mkdirSync(path.join(TARGET, name), { recursive: true });
  writeFileSync(destination, sql);
  written++;
}

// A migration deleted from supabase/migrations must not linger here, or Prisma
// would keep offering to apply a file nobody can find.
const expected = new Set(sources.map((file) => file.replace(/\.sql$/, '')));
let removed = 0;
for (const entry of readdirSync(TARGET, { withFileTypes: true })) {
  if (!entry.isDirectory() || expected.has(entry.name)) continue;
  rmSync(path.join(TARGET, entry.name), { recursive: true, force: true });
  removed++;
}

const parts = [`${sources.length} migration${sources.length === 1 ? '' : 's'} in sync`];
if (written) parts.push(`${written} written`);
if (removed) parts.push(`${removed} removed`);
console.log(parts.join(', ') + '.');
